"""Auto-load block for a print whose body never changes tool.

Field report (1.27b, 2x ACE Pro, multi): a one-colour PETG export, the
preflight assigned ACE 2 / Slot 1 to head 1, but the processed file had no
auto-load block and the head printed the PLA it held. Orca writes no tool
change for a single filament, so the only T lines sit in the start gcode,
and the rewrite dropped their ACE slot there.
"""
import importlib.util
import os

import pytest

PP = os.path.join(os.path.dirname(__file__), '..', '..', 'multiace', 'tools',
                  'post_process_virtual_toolheads.py')


@pytest.fixture(scope='module')
def pp():
    spec = importlib.util.spec_from_file_location('pp_single_tool', PP)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


SINGLE = """; HEADER_BLOCK_START
; generated by OrcaSlicer
; HEADER_BLOCK_END
M104 S240 T0
T0
M109 S240 T0
T0
SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0

; draw the starting line
G1 X10 Y10 E5 F600
;LAYER_CHANGE
;Z:0.2
G1 X20 Y20 E1
;LAYER_CHANGE
;Z:0.4
G1 X30 Y30 E1
"""

MULTI = """; generated by OrcaSlicer
M104 S220 T0
T0
SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0

; draw the starting line
G1 X10 Y10 E5 F600
; Change Tool 0 -> Tool 0 (layer -1)
T0
;LAYER_CHANGE
G1 X20 Y20 E1
; Change Tool 0 -> Tool 1
T1
G1 X30 Y30 E1
"""


def _run(pp, tmp_path, text, remap):
    src = tmp_path / 'in.gcode'
    src.write_text(text)
    a, b, c = (tmp_path / n for n in ('a.gcode', 'b.gcode', 'c.gcode'))
    pp.apply_remap_to_file(str(src), str(a), remap)
    pp.rewrite_to_file(str(a), str(b))
    pp.inject_auto_load_to_file(str(b), str(c))
    return c.read_text()


def _block(out):
    lines = out.splitlines()
    i = lines.index(next(l for l in lines
                         if l.startswith('; multiACE auto-load: load')))
    j = lines.index('; multiACE auto-load: end')
    return lines[i:j + 1]


def test_multi_single_colour_loads_the_assigned_slot(pp, tmp_path):
    # slicer T0 -> virtual 4 = ACE 1 (internal) / slot 0 on head 0
    out = _run(pp, tmp_path, SINGLE, {0: 4})
    block = _block(out)
    assert 'ACE_SWAP_HEAD HEAD=0 ACE=1 SLOT=0 INITIAL=1' in block
    assert '; multiACE processed: format=%d' % pp.PP_FORMAT_VERSION in block


def test_multi_single_colour_without_remap_loads_slot_of_head(pp, tmp_path):
    out = _run(pp, tmp_path, SINGLE, {})
    assert 'ACE_SWAP_HEAD HEAD=0 ACE=0 SLOT=0 INITIAL=1' in _block(out)


def test_multi_colour_block_unchanged_by_the_mark(pp, tmp_path):
    out = _run(pp, tmp_path, MULTI, {0: 4, 1: 1})
    block = _block(out)
    swaps = [l for l in block if l.startswith('ACE_SWAP_HEAD')]
    assert swaps == ['ACE_SWAP_HEAD HEAD=0 ACE=1 SLOT=0 INITIAL=1',
                     'ACE_SWAP_HEAD HEAD=1 ACE=0 SLOT=1 INITIAL=1']


def test_head_mode_single_colour_loads_the_assigned_slot(pp, tmp_path):
    src = tmp_path / 'in.gcode'
    src.write_text(SINGLE)
    b, c = tmp_path / 'b.gcode', tmp_path / 'c.gcode'
    assignment = {0: {'kind': 'ace', 'head': 2, 'ace': 3, 'slot': 1}}
    pp.rewrite_head_mode_to_file(str(src), str(b), assignment)
    pp.inject_auto_load_to_file(str(b), str(c), only_heads={2})
    block = _block(c.read_text())
    assert 'ACE_SWAP_HEAD HEAD=2 ACE=3 SLOT=1 INITIAL=1' in block
    assert 'SM_PRINT_PREEXTRUDE_FILAMENT INDEX=2 FORCE=1' in block
