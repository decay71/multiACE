"""Auto-load block for a print whose body never changes tool.

Field report (1.27b, 2x ACE Pro, multi): a one-colour PETG export, the
preflight assigned ACE 2 / Slot 1 to head 1, but the processed file had no
auto-load block and the head printed the PLA it held. Orca writes no tool
change for a single filament, so the only T lines sit in the start gcode,
and the rewrite dropped their ACE slot there.
"""
import importlib.util
import os

import pytest

PP = os.path.join(os.path.dirname(__file__), '..', '..', 'multiace', 'tools',
                  'post_process_virtual_toolheads.py')


@pytest.fixture(scope='module')
def pp():
    spec = importlib.util.spec_from_file_location('pp_single_tool', PP)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


SINGLE = """; HEADER_BLOCK_START
; generated by OrcaSlicer
; HEADER_BLOCK_END
M104 S240 T0
T0
M109 S240 T0
T0
SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0

; draw the starting line
G1 X10 Y10 E5 F600
;LAYER_CHANGE
;Z:0.2
G1 X20 Y20 E1
;LAYER_CHANGE
;Z:0.4
G1 X30 Y30 E1
"""

MULTI = """; generated by OrcaSlicer
M104 S220 T0
T0
SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0

; draw the starting line
G1 X10 Y10 E5 F600
; Change Tool 0 -> Tool 0 (layer -1)
T0
;LAYER_CHANGE
G1 X20 Y20 E1
; Change Tool 0 -> Tool 1
T1
G1 X30 Y30 E1
"""


def _run(pp, tmp_path, text, remap):
    src = tmp_path / 'in.gcode'
    src.write_text(text)
    a, b, c = (tmp_path / n for n in ('a.gcode', 'b.gcode', 'c.gcode'))
    pp.apply_remap_to_file(str(src), str(a), remap)
    pp.rewrite_to_file(str(a), str(b))
    pp.inject_auto_load_to_file(str(b), str(c))
    return c.read_text()


def _block(out):
    lines = out.splitlines()
    i = lines.index(next(l for l in lines
                         if l.startswith('; multiACE auto-load: load')))
    j = lines.index('; multiACE auto-load: end')
    return lines[i:j + 1]


def test_multi_single_colour_loads_the_assigned_slot(pp, tmp_path):
    # slicer T0 -> virtual 4 = ACE 1 (internal) / slot 0 on head 0
    out = _run(pp, tmp_path, SINGLE, {0: 4})
    block = _block(out)
    assert 'ACE_SWAP_HEAD HEAD=0 ACE=1 SLOT=0 INITIAL=1' in block
    assert '; multiACE processed: format=%d' % pp.PP_FORMAT_VERSION in block


def test_multi_single_colour_without_remap_loads_slot_of_head(pp, tmp_path):
    out = _run(pp, tmp_path, SINGLE, {})
    assert 'ACE_SWAP_HEAD HEAD=0 ACE=0 SLOT=0 INITIAL=1' in _block(out)


def test_multi_colour_block_unchanged_by_the_mark(pp, tmp_path):
    out = _run(pp, tmp_path, MULTI, {0: 4, 1: 1})
    block = _block(out)
    swaps = [l for l in block if l.startswith('ACE_SWAP_HEAD')]
    assert swaps == ['ACE_SWAP_HEAD HEAD=0 ACE=1 SLOT=0 INITIAL=1',
                     'ACE_SWAP_HEAD HEAD=1 ACE=0 SLOT=1 INITIAL=1']


def test_head_mode_single_colour_loads_the_assigned_slot(pp, tmp_path):
    src = tmp_path / 'in.gcode'
    src.write_text(SINGLE)
    b, c = tmp_path / 'b.gcode', tmp_path / 'c.gcode'
    assignment = {0: {'kind': 'ace', 'head': 2, 'ace': 3, 'slot': 1}}
    pp.rewrite_head_mode_to_file(str(src), str(b), assignment)
    pp.inject_auto_load_to_file(str(b), str(c), only_heads={2})
    block = _block(c.read_text())
    assert 'ACE_SWAP_HEAD HEAD=2 ACE=3 SLOT=1 INITIAL=1' in block
    assert 'SM_PRINT_PREEXTRUDE_FILAMENT INDEX=2 FORCE=1 TEMP=240' in block


def _scan(pp, tmp_path, gcode, head_of, body=True, reasons=None):
    # The same-head rule runs in the print body only; a layer marker in
    # front puts these samples there. Line numbers stay those of `gcode`.
    src = tmp_path / 'cool.gcode'
    src.write_text(gcode)
    if body:
        src.write_text('; LAYER_CHANGE\n' + gcode)
        got = pp.scan_cooling_standbys(str(src), head_of, reasons)
        if reasons is not None:
            moved = {k - 1: v for k, v in reasons.items()}
            reasons.clear()
            reasons.update(moved)
        return {n - 1 for n in got}
    return pp.scan_cooling_standbys(str(src), head_of, reasons)


def test_cooldown_dropped_when_next_toolchange_stays_on_the_head(pp, tmp_path):
    gcode = ("T0\nM104 S220 T0\nG1 X10 Y10 E1\n"
             "M104 S200 T0 ; set nozzle temperature ;cooldown\n"
             "T1\nM109 S220 T1\nG1 X20 Y20 E1\n")
    assert _scan(pp, tmp_path, gcode, lambda t: 0) == {3}


def test_cooldown_without_comment_is_seen_by_the_lower_target(pp, tmp_path):
    gcode = ("T0\nM104 S220 T0\nG1 X10 Y10 E1\nM104 S200 T0\n"
             "T1\nM109 S220 T1\nG1 X20 Y20 E1\n")
    assert _scan(pp, tmp_path, gcode, lambda t: 0) == {3}


def test_cooldown_kept_when_the_next_toolchange_parks_the_head(pp, tmp_path):
    gcode = ("T0\nM104 S220 T0\nG1 X10 Y10 E1\n"
             "M104 S200 T0 ;cooldown\nT1\nM109 S220 T1\nG1 X20 Y20 E1\n")
    assert _scan(pp, tmp_path, gcode, lambda t: t) == set()


def test_standby_of_a_parked_head_is_kept(pp, tmp_path):
    # T2 shares head 1 with T1 and is the next toolchange, but head 1 is
    # parked while head 0 prints: its standby is the ooze guard.
    gcode = ("T1\nM104 S220 T1\nG1 X5 Y5 E1\nT0\nM109 S220 T0\n"
             "M104 S200 T1 ;cooldown\nG1 X10 Y10 E1\n"
             "T2\nM109 S220 T2\nG1 X20 Y20 E1\n")
    assert _scan(pp, tmp_path, gcode, {0: 0, 1: 1, 2: 1}.get) == set()


def test_shutdown_of_the_printing_head_is_never_dropped(pp, tmp_path):
    gcode = ("T0\nM104 S220 T0\nG1 X10 Y10 E1\nM104 S0 T0\n"
             "T1\nM109 S220 T1\nG1 X20 Y20 E1\n")
    assert _scan(pp, tmp_path, gcode, lambda t: 0) == set()


def test_dropped_cooldown_does_not_count_as_the_head_target(pp, tmp_path):
    # The S90 line is dropped, so the head stays at 220 and the extrusion
    # after the swap is not an under-temperature case of its own.
    gcode = ("T0\nM104 S220 T0\nG1 X10 Y10 E1\nM104 S90 T0 ;cooldown\n"
             "T1\nG1 X20 Y20 E1\n")
    assert _scan(pp, tmp_path, gcode, lambda t: 0) == {3}


# Snapmaker Orca start G-code: cooldowns before cleaning, Z homing and bed
# probing, then the same head is picked again. Issue #254: the same-head
# rule dropped them and the head homed and probed at print temperature.
START_COOLDOWNS = """T1
M109 T1 S220
M104 T1 S130
T1
M109 T1 S130
G28 Z
BED_MESH_CALIBRATE
T1
M109 T1 S220
G1 X10 E1
"""


def test_start_gcode_cooldowns_are_kept(pp, tmp_path):
    assert _scan(pp, tmp_path, START_COOLDOWNS, lambda t: t,
                 body=False) == set()


def test_start_cooldowns_kept_but_body_rule_still_works(pp, tmp_path):
    gcode = START_COOLDOWNS + (
        "; LAYER_CHANGE\nT1\nM104 S220 T1\nG1 X10 Y10 E1\n"
        "M104 S200 T1 ;cooldown\nT2\nM109 S220 T2\nG1 X20 Y20 E1\n")
    lines = gcode.splitlines()
    reasons = {}
    got = _scan(pp, tmp_path, gcode, lambda t: 1, body=False,
                reasons=reasons)
    assert got == {lines.index("M104 S200 T1 ;cooldown")}
    assert set(reasons.values()) == {'swap'}


def test_dropped_lines_say_why(pp):
    swap = pp._dropped_standby_comment('M104 S200 T1', 'swap')
    cold = pp._dropped_standby_comment('M104 S90 T1', 'cold')
    assert 'cooldown before a swap on the same head' in swap
    assert 'below 170 C' in cold


def _prime(pp, tmp_path, gcode):
    src = tmp_path / 'p.gcode'
    src.write_text(gcode)
    out = tmp_path / 'p_out.gcode'
    pp.inject_auto_load_to_file(str(src), str(out), only_heads={0, 1})
    return [l for l in _block(out.read_text())
            if l.startswith('SM_PRINT_PREEXTRUDE')]


def test_block_prime_takes_the_print_temp_after_a_170_preheat(pp, tmp_path):
    gcode = ("M104 S170 T0\n\n; draw the starting line\n"
             "T0\nACE_SWAP_HEAD HEAD=0 ACE=0 SLOT=0\nM109 S215 T0\n"
             "G1 X10 Y10 E1\nT1\nACE_SWAP_HEAD HEAD=1 ACE=0 SLOT=1\n"
             "M109 S250 T1\nG1 X20 Y20 E1\n")
    assert _prime(pp, tmp_path, gcode) == [
        'SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0 FORCE=1 TEMP=215']


def test_block_prime_keeps_a_print_temp_set_before_the_block(pp, tmp_path):
    gcode = ("M109 S240 T0\n\n; draw the starting line\n"
             "T0\nACE_SWAP_HEAD HEAD=0 ACE=0 SLOT=0\nM104 S220 T0\n"
             "G1 X10 Y10 E1\n")
    assert _prime(pp, tmp_path, gcode) == [
        'SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0 FORCE=1 TEMP=240']


def test_block_prime_falls_back_to_220_without_a_target(pp, tmp_path):
    gcode = ("M104 S170 T0\n\n; draw the starting line\n"
             "T0\nACE_SWAP_HEAD HEAD=0 ACE=0 SLOT=0\nG1 X10 Y10 E1\n")
    assert _prime(pp, tmp_path, gcode) == [
        'SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0 FORCE=1 TEMP=220']


# Multi mode, start G-code with its own pre-extrude ahead of the auto-load
# block (field report 2026-11-22, Orca plugin, empty start head 4): stock
# primed the still empty head and the runout check stopped the print before
# the block loaded it. The prime now runs behind the loads.
def test_multi_start_preextrude_moves_behind_the_loads(pp, tmp_path):
    out = _run(pp, tmp_path, MULTI, {0: 4, 1: 1})
    lines = out.splitlines()
    block = _block(out)
    first = lines.index(block[0])
    pre = [l for l in lines[:first]
           if l.startswith('SM_PRINT_PREEXTRUDE_FILAMENT')]
    assert pre == []
    assert any(l.startswith('; multiACE moved into the auto-load block: '
                            'SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0')
               for l in lines[:first])
    swaps = [i for i, l in enumerate(block) if l.startswith('ACE_SWAP_HEAD')]
    prime = [i for i, l in enumerate(block)
             if l == 'SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0 FORCE=1 TEMP=220']
    assert prime and prime[0] > max(swaps)


def test_multi_without_start_preextrude_gets_no_extra_prime(pp, tmp_path):
    text = MULTI.replace('SM_PRINT_PREEXTRUDE_FILAMENT INDEX=0\n', '')
    block = _block(_run(pp, tmp_path, text, {0: 4, 1: 1}))
    assert not any(l.startswith('SM_PRINT_PREEXTRUDE') for l in block)
